const text = (
  name: string,
  label: string,
  required = true,
  maxLength = 100,
): CrudField => ({ name, label, required, maxLength })
const number = (name: string, label: string, min = 0): CrudField => ({
  name,
  label,
  kind: 'number',
  required: true,
  min,
})
const select = (name: string, label: string, values: string[]): CrudField => ({
  name,
  label,
  kind: 'select',
  required: true,
  options: values.map((value) => ({ value, label: value })),
})
const ref = (
  name: string,
  label: string,
  lookup: string,
  lookupLabel = 'name',
  required = true,
): CrudField => ({
  name,
  label,
  kind: 'select',
  required,
  lookup,
  lookupLabel,
})
const date = (name: string, label: string): CrudField => ({
  name,
  label,
  kind: 'date',
  required: true,
})
const columns = (...items: [string, string][]) =>
  items.map(([key, label]) => ({ key, label }))
