const text = (
  name: string,
  label: string,
  required = true,
  maxLength = 100,
): CrudField => ({ name, label, required, maxLength })
const number = (name: string, label: string, min = 0): CrudField => ({
  name,
  label,
  kind: 'number',
  required: true,
  min,
})
const select = (name: string, label: string, values: string[]): CrudField => ({
  name,
  label,
  kind: 'select',
  required: true,
  options: values.map((value) => ({ value, label: value })),
})
const ref = (
  name: string,
  label: string,
  lookup: string,
  lookupLabel = 'name',
  required = true,
): CrudField => ({
  name,
  label,
  kind: 'select',
  required,
  lookup,
  lookupLabel,
})
const date = (name: string, label: string): CrudField => ({
  name,
  label,
  kind: 'date',
  required: true,
})
const columns = (...items: [string, string][]): CrudColumn[] =>
  items.map(([key, label]) => ({ key, label }))
const money = (key: string, label: string): CrudColumn => ({
  key,
  label,
  format: 'money',
  align: 'right',
})
const count = (key: string, label: string): CrudColumn => ({
  key,
  label,
  format: 'number',
  align: 'right',
})
const dateColumn = (key: string, label: string): CrudColumn => ({
  key,
  label,
  format: 'date',
})
const monthColumn = (key: string, label: string): CrudColumn => ({
  key,
  label,
  format: 'month',
})
const booleanFilter = (name: string, label: string, yes = 'Có', no = 'Không'): CrudField => ({
  name, label, kind: 'select', filterValueType: 'boolean',
  options: [{ value: 'true', label: yes }, { value: 'false', label: no }],
})
const statusFilter = (values: string[]): CrudField => ({
  ...select('status', 'Trạng thái', values), required: false,
})
const facultyRef = (required = false): CrudField => ({
  ...ref('facultyId', 'Khoa', '/catalogs/faculties', 'name', required),
  lookupDependsOn: { field: 'schoolId', required: true },
})
const floorRef = (required = true): CrudField => ({
  ...ref('floor', 'Tầng', '/floors', 'name', required),
  lookupValue: 'floor',
  lookupDependsOn: { field: 'buildingId', required: true },
})
