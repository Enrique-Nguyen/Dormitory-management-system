CREATE TABLE storage_location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    management_unit_id BIGINT NOT NULL REFERENCES management_unit(id),
    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ux_storage_location_unit_code UNIQUE (management_unit_id, code),
    CONSTRAINT ux_storage_location_unit_name UNIQUE (management_unit_id, name)
);

-- Keep the complete legacy label; ownership comes only from the previous bed.
INSERT INTO storage_location (management_unit_id, code, name)
SELECT management_unit_id, 'LEGACY-' || row_number() OVER (ORDER BY management_unit_id, location), location
FROM (
    SELECT DISTINCT b.management_unit_id, s.location
    FROM storage_record s
    JOIN bed bd ON bd.id = s.previous_bed_id
    JOIN room r ON r.id = bd.room_id
    JOIN building b ON b.id = r.building_id
) legacy;

ALTER TABLE storage_record ADD COLUMN location_id BIGINT;
UPDATE storage_record s
SET location_id = l.id
FROM bed bd
JOIN room r ON r.id = bd.room_id
JOIN building b ON b.id = r.building_id
JOIN storage_location l ON l.management_unit_id = b.management_unit_id
WHERE bd.id = s.previous_bed_id AND l.name = s.location;

ALTER TABLE storage_record ALTER COLUMN location_id SET NOT NULL;
ALTER TABLE storage_record ADD CONSTRAINT fk_storage_record_location
    FOREIGN KEY (location_id) REFERENCES storage_location(id);
CREATE INDEX ix_storage_record_location ON storage_record(location_id);

-- Preserve the existing view contract before removing its source text column.
CREATE OR REPLACE VIEW v_summer_leave AS
SELECT s.contract_id,
       c.student_id,
       s.id AS storage_record_id,
       s.package_count,
       l.name AS location,
       s.deposited_at,
       s.previous_bed_id,
       NOT EXISTS (SELECT 1 FROM room_assignment_history a
                   WHERE a.bed_id = s.previous_bed_id AND a.ended_at IS NULL) AS previous_bed_free,
       s.location_id
FROM storage_record s
JOIN storage_location l ON l.id = s.location_id
JOIN dormitory_contract c ON c.id = s.contract_id
WHERE s.returned_at IS NULL AND c.status = 'ACTIVE';

ALTER TABLE storage_record DROP COLUMN location;
